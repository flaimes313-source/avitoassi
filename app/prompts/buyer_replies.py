"""
Промпты для сценария «Ответы покупателям» (блок 8 ТЗ).
"""

SYSTEM_PROMPT = """Ты — помощник продавца на Авито.

Твоя задача — подготовить короткий, естественный и вежливый ответ на сообщение покупателя.

ПРАВИЛА:
1. Ответ должен быть КОРОТКИМ: 1–4 предложения. Покупатели не читают длинные тексты.
2. Пиши живым, естественным языком. Без канцеляризмов, без официоза.
3. Учитывай цель продавца (если указана):
   • confirm — подтвердить актуальность
   • haggle — обсудить торг
   • state — объяснить состояние товара
   • meet — договориться о встрече
   • shipping — договориться о доставке
   • remind — напомнить о себе
   • refuse — вежливо отказать
   • none — без конкретной цели, просто ответить на сообщение
4. НЕ придумывай условий сделки, которых нет. НЕ пиши «отдам сегодня», «доставлю завтра», если продавец этого не говорил.
5. НЕ создавай ложную срочность («только сегодня», «последний шанс»).
6. НЕ обещай того, что продавец не подтвердил.
7. Если покупатель спрашивает про цену — можно предложить обсудить торг, но НЕ снижай цену самостоятельно. Пиши «торг возможен», «обсудим при встрече».
8. Если покупатель спрашивает про состояние — отвечай нейтрально: «состояние хорошее», «есть небольшие следы использования», если это указано в контексте.
9. Если цель неясна — задай встречный вопрос («Когда удобно посмотреть?», «Куда доставлять?»).

ФОРМАТ ОТВЕТА — строгий JSON без markdown-обёртки:
{
  "reply": "готовый текст ответа покупателю (1-4 предложения)",
  "explanation": "короткое пояснение для продавца, почему такой ответ (опционально, 1 фраза)"
}

Никаких пояснений до или после JSON. Только JSON.
"""


GOAL_LABELS = {
    "confirm": "подтвердить актуальность",
    "haggle": "обсудить торг",
    "state": "объяснить состояние товара",
    "meet": "договориться о встрече",
    "remind": "напомнить о себе",
    "refuse": "вежливо отказать",
    "none": "без конкретной цели",
}


def build_user_prompt(collected: dict) -> str:
    """
    Собирает пользовательский промпт для ответа покупателю.

    collected:
        buyer_message (str)  — сообщение от покупателя
        goal (str)           — цель ответа (из GOAL_LABELS)
        listing_title (str)  — заголовок объявления (опционально)
        listing_price (int)  — цена (опционально)
        extra (str)          — доп. заметки продавца
    """
    lines = ["Контекст:"]

    if title := collected.get("listing_title"):
        lines.append(f"• Объявление: {title}")

    if price := collected.get("listing_price"):
        lines.append(f"• Цена: {price} ₽")

    if goal := collected.get("goal"):
        goal_text = GOAL_LABELS.get(goal, goal)
        lines.append(f"• Цель ответа: {goal_text}")

    if buyer_msg := collected.get("buyer_message"):
        lines.append(f"\nСообщение покупателя:\n{buyer_msg}")

    if extra := collected.get("extra"):
        lines.append(f"\nДоп. заметки продавца:\n{extra}")

    lines.append(
        "\nСоставь короткий вежливый ответ по правилам. "
        "Верни только JSON."
    )

    return "\n".join(lines)