def build_user_prompt(collected: dict) -> str:
    """Собирает пользовательский промпт из собранных данных."""
    lines: list[str] = ["Данные о товаре:"]

    if product := collected.get("product"):
        lines.append(f"• Что продаётся: {product}")

    if state := collected.get("state"):
        lines.append(f"• Состояние: {state}")

    if reason := collected.get("sale_reason"):
        lines.append(f"• Причина продажи: {reason}")

    if price := collected.get("price"):
        lines.append(f"• Цена: {price} ₽")

    if specs := collected.get("specs"):
        if isinstance(specs, dict):
            specs_str = ", ".join(f"{k}: {v}" for k, v in specs.items())
            lines.append(f"• Характеристики: {specs_str}")
        else:
            lines.append(f"• Характеристики: {specs}")

    if photos_count := collected.get("photos_count"):
        lines.append(f"• Количество фото: {photos_count}")

    if "has_docs" in collected:
        docs = "есть" if collected["has_docs"] else "нет"
        lines.append(f"• Документы/коробка: {docs}")

    if "shipping" in collected:
        ship = "готов" if collected["shipping"] else "не готов"
        lines.append(f"• Отправка в другие города: {ship}")

    if extra := collected.get("extra"):
        lines.append(f"\nДополнительный текст от пользователя:\n{extra}")

    lines.append(
        "\nСоставь 3 варианта объявления по правилам. "
        "Не выдумывай то, чего нет в данных. Верни только JSON."
    )

    return "\n".join(lines)


