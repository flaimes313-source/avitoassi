"""
Промпты для сценария «Создать объявление» (блок 3 ТЗ).
"""

SYSTEM_PROMPT = """Ты — профессиональный авитолог и помощник частного продавца на Авито.

Твоя задача — помочь пользователю составить понятное, привлекательное и правдивое объявление.

ПРАВИЛА:
1. НЕ выдумывай характеристики, причину продажи, гарантию, дату покупки или преимущества товара. Используй только то, что сообщил пользователь. Неизвестные сведения либо пропускай, либо пометь как «уточнить у продавца».
2. Создавай РОВНО 3 варианта с разными подходами:
   • Фактический — строго по фактам, лаконично, без эмоций.
   • Дружелюбный — тёплый тон, релевантные поисковые слова (по которым ищут такой товар).
   • Альтернативный — другой угол подачи: например, акцент на выгоду, логистику или срочность. Если уместен.
3. Пиши естественно, без пустых рекламных обещаний. Не гарантируй просмотры и продажи.
4. В каждом варианте: сначала заголовок (до 50 символов), затем основной текст.
5. Структура текста каждого варианта:
   • Первый абзац: что продаёшь, состояние, причина продажи (если указана).
   • Второй блок: ключевые характеристики и выгоды.
   • Третий блок: условия сделки (самовывоз / доставка / оплата / торг / призыв к действию).
6. В каждом заголовке обязательно указывай ключевой параметр (размер, ширина, модель, объём памяти и т.п.), если он известен.
7. Если пользователь готов отправлять в другие города — в третьем варианте укажи варианты доставки: СДЭК, ПЭК, Деловые Линии, Почта России.

ФОРМАТ ОТВЕТА — строгий JSON, без markdown-обёртки:
{
  "variants": [
    {
      "approach": "factual",
      "title": "заголовок до 50 символов",
      "body": "полный текст объявления"
    },
    {
      "approach": "friendly",
      "title": "заголовок до 50 символов",
      "body": "полный текст объявления"
    },
    {
      "approach": "alternative",
      "title": "заголовок до 50 символов",
      "body": "полный текст объявления"
    }
  ]
}

Никаких пояснений до или после JSON. Только JSON.
"""


def build_user_prompt(collected: dict) -> str:
    """
    Собирает пользовательский промпт из собранных данных.

    collected — словарь из tasks.collected_data:
        product (str)         — что продаётся
        state (str)           — состояние (новое/б/у/после ремонта)
        sale_reason (str)     — причина продажи
        price (int|str)       — цена
        specs (dict)          — подтверждённые характеристики
        photos_count (int)    — сколько фото
        has_docs (bool)       — есть ли документы/коробка
        shipping (bool)       — готов ли отправлять в другие города
        extra (str)           — дополнительный текст от пользователя
    """
    lines: list[str] = ["Данные о товаре:"]

    if product := collected.get("product"):
        lines.append(f"• Что продаётся: {product}")

    if state := collected.get("state"):
        lines.append(f"• Состояние: {state}")

    if reason := collected.get("sale_reason"):
        lines.append(f"• Причина продажи: {reason}")

    if price := collected.get("price"):
        lines.append(f"• Цена: {price} ₽")

    if specs := collected.get("specs"):
        if isinstance(specs, dict):
            specs_str = ", ".join(f"{k}: {v}" for k, v in specs.items())
            lines.append(f"• Характеристики: {specs_str}")
        else:
            lines.append(f"• Характеристики: {specs}")

    if photos_count := collected.get("photos_count"):
        lines.append(f"• Количество фото: {photos_count}")

    if "has_docs" in collected:
        docs = "есть" if collected["has_docs"] else "нет"
        lines.append(f"• Документы/коробка: {docs}")

    if "shipping" in collected:
        ship = "готов" if collected["shipping"] else "не готов"
        lines.append(f"• Отправка в другие города: {ship}")

    if extra := collected.get("extra"):
        lines.append(f"\nДополнительный текст от пользователя:\n{extra}")

    lines.append(
        "\nСоставь 3 варианта объявления по правилам. "
        "Не выдумывай то, чего нет в данных. Верни только JSON."
    )

    return "\n".join(lines)