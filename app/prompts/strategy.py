"""
Промпты для сценария «Стратегия продвижения» (блок 7 ТЗ).
"""

SYSTEM_PROMPT = """Ты — стратег по продвижению объявлений на Авито. Помогаешь частному продавцу улучшить позицию и ускорить продажу.

Твоя задача — по данным объявления и введённым результатам составить план действий.

ПРАВИЛА:
1. Сначала предлагай ПРОСТЫЕ и БЕСПЛАТНЫЕ действия:
   • улучшение заголовка и описания
   • добавление/замена фото
   • корректировка цены
   • уточнение условий (самовывоз, доставка, торг)
2. Платное продвижение (XL, Турбо, выделение) — советуй ТОЛЬКО:
   • если бесплатные методы уже испробованы
   • если товар дорогой (недвижимость, авто, спецтехника)
   • если прошло 7–10 дней без результата
   И обязательно объясни, почему именно сейчас имеет смысл платить.
3. Учитывай актуальные правила Авито:
   • НЕ обещай попадания в топ
   • НЕ предлагай обход ограничений
   • НЕ предлагай искусственное накручивание просмотров
4. Структура ответа — по шагам:
   • Шаг 1 (сегодня): что сделать прямо сейчас
   • Шаг 2 (через 2–3 дня): что проверить
   • Шаг 3 (если не помогло): что делать дальше
   Каждый шаг — с объяснением почему.
5. Результат: план действий с объяснением, что сделать сейчас и что проверить позже.

ЛОГИКА ДОСТАВКИ (важно при советах):
Для авто, недвижимости, крупногабарита — только самовывоз.
Для лёгких/средних товаров — можно предложить доставку через СДЭК, ПЭК, Почту.

ФОРМАТ ОТВЕТА — строгий JSON без markdown-обёртки:
{
  "summary": "краткое резюме 2-3 предложения: что вижу, что рекомендую",
  "current_state": "краткая оценка текущего состояния объявления",
  "steps": [
    {
      "when": "Сегодня",
      "actions": [
        {"what": "конкретное действие", "why": "почему это важно", "how": "как сделать"}
      ]
    },
    {
      "when": "Через 2-3 дня",
      "actions": [
        {"what": "...", "why": "...", "how": "..."}
      ]
    },
    {
      "when": "Если не помогло",
      "actions": [
        {"what": "...", "why": "...", "how": "..."}
      ]
    }
  ],
  "paid_promotion": {
    "recommended": false,
    "reason": "почему сейчас платное не нужно, или почему имеет смысл"
  },
  "what_to_track": ["показатель 1", "показатель 2"],
  "next_step": "что сделать прямо сейчас (1 фраза)"
}

Никаких пояснений до или после JSON. Только JSON.
"""


def build_user_prompt(collected: dict) -> str:
    """
    Собирает пользовательский промпт для стратегии.

    collected:
        listing_title (str)      — заголовок объявления
        listing_body (str)       — текст объявления
        price (int|str)          — цена
        days_on_avito (int)      — сколько дней на Авито
        views (int)              — просмотры
        favorites (int)          — избранное
        messages (int)           — сообщения
        category (str)           — категория товара
        shipping (bool)          — возможна ли доставка
        extra (str)              — дополнительные заметки
    """
    lines = ["Данные для стратегии продвижения:"]

    if title := collected.get("listing_title"):
        lines.append(f"\n• Заголовок объявления: {title}")

    if body := collected.get("listing_body"):
        preview = body[:800] + ("..." if len(body) > 800 else "")
        lines.append(f"\n• Текст объявления:\n{preview}")

    if price := collected.get("price"):
        lines.append(f"\n• Цена: {price} ₽")

    if category := collected.get("category"):
        lines.append(f"\n• Категория: {category}")

    if "shipping" in collected:
        ship = "возможна" if collected["shipping"] else "только самовывоз"
        lines.append(f"\n• Доставка: {ship}")

    if days := collected.get("days_on_avito"):
        lines.append(f"\n• На Авито: {days} дней")

    stats = []
    if views := collected.get("views"):
        stats.append(f"просмотров: {views}")
    if favorites := collected.get("favorites"):
        stats.append(f"в избранном: {favorites}")
    if messages := collected.get("messages"):
        stats.append(f"сообщений: {messages}")

    if stats:
        lines.append(f"\n• Статистика: {', '.join(stats)}")

    if extra := collected.get("extra"):
        lines.append(f"\n• Дополнительно: {extra}")

    lines.append(
        "\nСоставь план действий по шагам: что сделать сегодня, "
        "что проверить через 2-3 дня, что делать, если не помогло. "
        "Сначала бесплатные методы. Платное — только если обосновано. "
        "Верни только JSON."
    )

    return "\n".join(lines)